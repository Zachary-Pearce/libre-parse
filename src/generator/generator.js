import { Tree } from '../parsing/tree.js';
import Token from '../parsing/token.js';

export default class Generator {
    /**
     * @param {Tree} ast - The abstract syntax tree to compile
     * @param {String} sourceText
     */
    constructor(ast, sourceText) {
        this.ast = ast;
        this.sourceText = sourceText;

        /**
         * @type {Object.<string, number>} A symbol table that relates a given terminal or non-terminal to a unique identifier.
         */
        this.symbolTable = {};

        /**
         * @type {Object.<number, RegExp>} The generated token regex expressions mapped to a unique identifier.
         */
        this.tokenRegex = {};

        /**
         * @type {Object.<number, Object.<number, Array<Number>>>} The generated parse table.
         */
        this.parseTable = {};

        /**
         * @type {Number} A pointer to keep track of rule number.
         */
        this.rulePointer = 1;

        /**
         * @type {Object.<Number, Array<Array<Number>>>} The production rules.
         */
        this.productionRules = {};
    }

    /**
     * Escape meta characters for literal values in regular expression.
     * 
     * @param {String} str
     * @returns {String} The escaped meta character.
     */
    _escapeRegex(str) {
        return str.replace(/[.*+?^${}()|\[\]\\]/g, '\\$&');
    }

    /**
     * Get the literal value of a terminal at the given text position.
     * 
     * @param {Number} pos - The position of the single or double quote marker.
     * @returns {String} The terminal string.
     */
    _getLiteralValue(pos) {
        const idTreeFrag = this.ast.getTreeFragment(pos, 9);

        const start = pos;
        let end = start;
        const quoteVal = idTreeFrag.root.children[0].val;
        const handleNodeVisted = (node) => {
            if (node.val === quoteVal && node.pos > start) {
                end = node.pos
                idTreeFrag.off('nodeVisited', handleNodeVisted);
            }
        }

        idTreeFrag.on('nodeVisited', handleNodeVisted);
        idTreeFrag.traverse();
        //return literal text not including first quote char
        return this.sourceText.substring(start + 1, end);
    }

    /**
     * Get the literal name of an identifier at the given text position.
     * 
     * @param {Number} pos
     * @returns {Array<Number>} Start and end position of name literal.
     */
    _getIdentifierLiteral(pos) {
        const idTreeFrag = this.ast.getTreeFragment(pos, 7);
        
        const start = pos;
        let end = start;
        const handleNodeVisted = (node) => {
            end = node.pos > end ? node.pos : end;
        }

        idTreeFrag.on('nodeVisited', handleNodeVisted);
        idTreeFrag.traverse();
        idTreeFrag.off('nodeVisited', handleNodeVisted);
        return [start, end];
    }

    /**
     * Add a given symbol and its unique identifer to the symbol table.
     * 
     * @param {String} literal - The literal name of the symbol.
     */
    _addToSymbolTable(literal) {
        this.symbolTable[literal] = this.rulePointer;
        this.rulePointer++;
    }

    /**
     * Add a terminals regular expression to the object.
     * 
     * @param {RegExp} regex
     */
    _addRegex(regex) {
        this.tokenRegex[this.rulePointer] = regex;
    }

    /**
     * Compile a line's tree fragment into a single RegExp.
     * 
     * @param {Number} pos - The position of the line in the grammar definition.
     * @returns {RegExp} The compiled regular expression.
     */
    _compileTokenRegex(pos) {
        const treeFragment = this.ast.getTreeFragment(pos, 2);

        const nodeResults = new Map();
        const nodeVisited = (node) => {
            //if there are previous regex fragments generated by this nodes children then consider these
            const childResults = node.children.map(child => {
                return nodeResults.get(child) || '';
            });
            let result = '';

            switch(node.val) {
                case 9:
                    const terminal = this._getLiteralValue(node.pos);
                    result = this._escapeRegex(terminal);
                    break;

                case 13: //alternation ("|")
                    result = childResults.join('|');
                    break;

                case 15: //concat (",")
                    result = childResults.join('');
                    break;

                case 11: //modifiers (*, +, ?)
                    if (node.children[0].val === 27) {
                        result = '?';
                    } else if (node.children[0].val === 28) {
                        result = '*';
                    } else if (node.children[0].val === 29) {
                        result = '+';
                    }
                    break;

                case 12: //join factors with modifiers
                    if (['?', '*', '+'].includes(childResults[1])) {
                        result = `(${childResults[0]})${childResults[1]}`;
                    //TODO: add logic for handling minus modifier
                    } else {
                        result = childResults.join('');
                    }
                    break;

                default: {
                    result = childResults.join('');
                    break;
                }
            }

            nodeResults.set(node, result);
        };

        treeFragment.on('nodeVisited', nodeVisited);
        treeFragment.traverse();
        treeFragment.off('nodeVisited', nodeVisited);

        return new RegExp(nodeResults.get(treeFragment.root));
    }

    /**
     * Get the production rule for a given non-terminal.
     * 
     * @param {Number} pos - The index position of the non-terminal.
     * @returns {Array<String>} The generated production rule in string form.
     */
    _getProdRule(pos) {
        const treeFragment = this.ast.getTreeFragment(pos, 2);

        let test = [];
        const nodeResults = new Map();
        let skippedLhs = false;
        const nodeVisted = (node) => {
            const childResults = node.children.map(child => nodeResults.get(child));
            let result = [];

            switch (node.val) {
                case 21: //open brackets ("(", "[", "{")
                    result = "(";
                    break;
                case 23:
                    result = "[";
                    break;
                case 25:
                    result = "{";
                    break;
                case 22: //close brackets (")", "]", "}")
                    result = ")";
                    break;
                case 24:
                    result = "]";
                    break;
                case 26:
                    result = "}";
                    break;

                case 13: //alteration ("|")
                    // result = childResults.join('|');
                    result = childResults.reduce((acc, curr, i) => {
                        if (i > 0) { acc.push("|") };
                        return acc.concat(curr);
                    }, []);
                    break;

                case 7: //identifier
                    if (!skippedLhs) {
                        skippedLhs = true;
                        break;
                    }

                    const [start, end] = this._getIdentifierLiteral(node.pos);
                    const literal = this.sourceText.substring(start, end + 1);
                    if (!this.symbolTable[literal]) {
                        this._addToSymbolTable(literal);
                    }
                    result = this.symbolTable[literal];
                    break;
                
                case 9: //terminal
                    const terminal = this._getLiteralValue(node.pos);
                    //create a new token regex for the terminal
                    const escapedTerminal = this._escapeRegex(terminal);
                    const regex = new RegExp(this._escapeRegex(escapedTerminal));
                    //does the terminal already exist in the symbol table?
                    if (this.symbolTable[terminal]) {
                        result = this.symbolTable[terminal];
                    } else {
                        //if not, check if terminal already exists in a token regex
                        for (const id of Object.keys(this.tokenRegex)) {
                            if (this.tokenRegex[id].source.includes(escapedTerminal)) {
                                //if it exists, we need to remove it from the regex
                                let newRegex = this.tokenRegex[id].source;
                                newRegex = newRegex.replace(regex, "");             //rid of the terminal from the existing pattern
                                newRegex = newRegex.replace(/(?<!\\)\|{2,}/g, "|"); //get rid of chains of consecutive "|"
                                newRegex = newRegex.replace(/^[\|]+|[\|]+$/g, "");  //get rid of trailing and leading "|"

                                //if we have removed tokens from an existing regex then the current production rules need to be updated to include these
                                //  e.g. Character | "_" | " " -> Character | "," | "_" | " " when "," is separated
                                const termVal = this.rulePointer;
                                for (const [lhs, rules] of Object.entries(this.productionRules)) {
                                    for (const rhs of rules) {
                                        let change = false;
                                        const temp = Array.from(rhs);
                                        for (let i = 0; i < temp.length; i++) {
                                            if (temp[i] === Number(id)) {
                                                temp[i] = termVal;
                                                change = true;
                                            }
                                        }

                                        if (change) {
                                            this.productionRules[lhs].push(temp);
                                        }
                                    }
                                }

                                this.tokenRegex[id] = new RegExp(newRegex);
                                break;
                            }
                        }

                        this._addRegex(new RegExp(escapedTerminal));
                        result = this.rulePointer;
                        this._addToSymbolTable(terminal);
                    }
                    break;

                default: {
                    // result = childResults.join('');
                    result = childResults.flat();
                    break;
                }
            }

            nodeResults.set(node, result);
        };

        treeFragment.on('nodeVisited', nodeVisted);
        treeFragment.traverse();
        treeFragment.off('nodeVisited', nodeVisted);

        return nodeResults.get(treeFragment.root);
    }

    /**
     * Compile a string-form production rule.
     * 
     * @param {String} stringRule
     * @returns {Array<Array<Number>>} The compiled production rules.
     */
    _compileProd(stringRule) {
        const prodRules = new Array();
        let rule = [];

        let i = 0;
        while (i < stringRule.length) {
            let char = stringRule[i];
            const start = i + 1;
            switch (char) {
                //no-modifier group
                case '(':
                    while (char != ')') {
                        i++;
                        char = stringRule[i];
                    }
                    //we will create a rule substring for the group then compile this
                    const groupRules = this._compileProd(stringRule.slice(start, i));
                    //there are two cases here, either:
                    // - there are multiple production rules produced
                    if (groupRules.length > 1) {
                        //a new non-terminal would need to be created here
                        //we do not need to add this to the symbol table though
                        this.productionRules[this.rulePointer] = new Array();
                        this.productionRules[this.rulePointer].push(...groupRules);
                        rule = [this.rulePointer];
                        this.rulePointer++;
                    // - or just one production rule is produced
                    } else {
                        //can be appended at the next '|' character
                        rule = groupRules[0];
                    }
                    break;

                //zero or more group
                case '{':
                    while (char != '}') {
                        i++;
                        char = stringRule[i];
                    }
                    //we will create a rule substring for the group then compile this
                    const repRules = this._compileProd(stringRule.slice(start, i));
                    //in this case we will always create a new rule
                    repRules.map((rule) => { rule.push(this.rulePointer); });
                    repRules.push([Token.EMPTY]);
                    this.productionRules[this.rulePointer] = new Array();
                    this.productionRules[this.rulePointer].push(...repRules);
                    rule.push(this.rulePointer);
                    this.rulePointer++;
                break;

                //optional group
                case '[':
                    while (char != ']') {
                        i++;
                        char = stringRule[i];
                    }
                    //we will create a rule substring for the group then compile this
                    const opRules = this._compileProd(stringRule.slice(start, i));
                    opRules.push([Token.EMPTY]);
                    //in this case we will always create a new rule
                    //a new non-terminal would need to be created here
                    //we do not need to add this to the symbol table though
                    this.productionRules[this.rulePointer] = new Array();
                    this.productionRules[this.rulePointer].push(...opRules);
                    rule = [this.rulePointer];
                    this.rulePointer++;
                break;

                case '|':
                    prodRules.push(rule);
                    rule = [];
                    break;
                
                default:
                    rule.push(Number(char));
                    break;
            }
            i++;
        }

        if (rule.length > 0) {
            prodRules.push(rule);
        }

        return prodRules;
    }

    /**
     * Compute the first of a given set of productions.
     * 
     * @param {Object.<Number, Array<Array<Number>>>} prodRules
     * @param {Number} symbol - The non-terminal symbol.
     * @returns {Array<Number>} The first set.
     */
    _getFirstSet(symbol) {
        const first = new Set();

        for (const rule of this.productionRules[symbol]) {
            const term = rule[0];

            if (this.productionRules[term]) {
                const childFirst = this._getFirstSet(term);
                childFirst.forEach((f) => {first.add(f)});
            } else {
                first.add(term);
            }
        }

        return Array.from(first);
    }

    /**
     * Compute the follow set for a given non-terminal.
     * 
     * @param {Number} symbol - The non-terminal symbol.
     * @returns {Array<Number>} The follow set.
     */
    _getFollowSet(symbol) {
        const follow = new Set();

        let symLiteral = "";
        for (const [literal, val] of Object.entries(this.symbolTable)) {
            if (val == symbol) {
                symLiteral = literal;
            }
        }
        if (symLiteral.slice(-1) === "_") { follow.add(Token.EOF); }
        
        for (const [lhs, rules] of Object.entries(this.productionRules)) {
            for (const rule of rules) {
                for (let i = 0; i < rule.length; i++) {
                    if (rule[i] !== symbol) { continue; }

                    const nextSymbol = rule[i + 1] || null;
                    if (nextSymbol) {
                        if (this.productionRules[nextSymbol]) {
                            const childFirst = this._getFirstSet(nextSymbol);
                            childFirst.forEach((f) => {if (f != Token.EMPTY) follow.add(f)});
                            //we also need to consider if the next thing could be empty
                            for (const aRule of this.productionRules[nextSymbol]) {
                                for (const sym of aRule) {
                                    if (sym === Token.EMPTY) {
                                        const advSymbol = rule[i + 2] || null;
                                        if (advSymbol) {
                                            const nextFirst = this._getFirstSet(advSymbol);
                                            nextFirst.forEach((f) => {if (f != Token.EMPTY) follow.add(f)});
                                        } else if (Number(lhs) !== nextSymbol) {
                                            const parentFollow = this._getFollowSet(Number(lhs));
                                            parentFollow.forEach((f) => {follow.add(f)});
                                        }
                                        break;
                                    }
                                }
                            }
                        } else {
                            follow.add(nextSymbol);
                        }
                    } else if (Number(lhs) !== symbol) {
                        const parentFollow = this._getFollowSet(Number(lhs));
                        parentFollow.forEach((f) => {follow.add(f)});
                    }
                }
            }
        }

        return Array.from(follow);
    }

    /**
     * Compile the abstract syntax tree into a parse table and regex strings.
     * 
     * @returns {Object.<number, RegExp>} tokenRegex
     * @returns {Object.<number, Object.<number, Array<number>>>} parseTable
     * @returns {Number} startSymbol
     */
    compile() {
        /**
         * @type {Array<Number>} The index positions of each line in the source text.
         */
        const linePositions = new Array();
        //split lines based on the position of the grammar nodes
        const nodeVisted = (node) => {
            //ignore grammar nodes that are empty
            if (node.val == 1 && node.children.length > 1) {
                linePositions.unshift(node.pos);
            }
        };
        this.ast.on('nodeVisited', nodeVisted);
        this.ast.traverse();
        this.ast.off('nodeVisited', nodeVisted);

        //first pass
        this.productionRules = {};
        let startSymbol = null;
        for (const i of linePositions) {
            const [start, end] = this._getIdentifierLiteral(i);
            const symbol = this.sourceText.substring(start, end + 1);
            //define whether or not we are looking at a non-terminal or terminal definition on this line (using identifier starting with a capital letter)
            if (symbol[0].toUpperCase() === symbol[0]) {
                //non-terminals after being processed will return an integer array representing the production rule. Done!
                const stringRules = this._getProdRule(i);
                const prodRules = this._compileProd(stringRules);
                //the production rule will need to be stored somewhere for later [lhs (the non-terminal identifier):rhs (the production rule)] for the purposes of calculating first and follow.
                //we will do this by adding to the productionRules variable with lhs being the numerical id
                if (this.symbolTable[symbol]) {
                    this.productionRules[this.symbolTable[symbol]] = new Array();
                    this.productionRules[this.symbolTable[symbol]].push(...prodRules);
                } else {
                    this.productionRules[this.rulePointer] = new Array();
                    this.productionRules[this.rulePointer].push(...prodRules);
                    this._addToSymbolTable(symbol);
                }

                if (symbol.slice(-1) === "_") {
                    if (startSymbol) { //if a start symbol is already defined...
                        throw new SyntaxError(`Multiple start symbols defined: ${startSymbol} and ${symbol}`);
                    }
                    //allocate start symbol
                    startSymbol = this.symbolTable[symbol];
                }
            } else {
                //terminals after being processed will return a token regex expression.
                const regex = this._compileTokenRegex(i);
                //add token regex to the tokenRegex object using current rule pointer.
                this._addRegex(regex);
                this._addToSymbolTable(symbol);
            }
        }

        //second pass
        //calculate the first and follow sets for each non-terminal symbol.
        for (const symbol of Object.keys(this.productionRules)) {
            //use the first and follow sets to create the parse table.
            // follows are used for adding production rules that result in empty tokens.
            // firsts will be used to decide where production rules will go in the parse table, just need to figure out how we decide what rule goes where.
            const entry = {};
            const first = this._getFirstSet(Number(symbol));

            //to get the parse table entry we need to loop through each first symbol in first
            for (const fst of first) {
                if (fst === Token.EMPTY) { continue; }

                //we find the production rule that relates to this first set
                for (const rl of this.productionRules[symbol]) {
                    const sym = rl[0];
                    if (this.productionRules[sym]) {
                        //if we are looking at a non-terminal, get the first set
                        const childFirst = this._getFirstSet(sym);
                        if (childFirst.includes(fst)) {
                            //if this first set includes fst then we found the rule
                            entry[fst] = rl;
                        }
                    } else {
                        if (sym === fst) {
                            entry[fst] = rl;
                        }
                    }
                }
            }

            //if the first set includes an empty token then add follows to parse table
            if (first.includes(Token.EMPTY)) {
                const follow = this._getFollowSet(Number(symbol));
                for (const flw of follow) {
                    entry[flw] = [Token.EMPTY];
                }
            }

            this.parseTable[symbol] = entry;
        }

        //then finally we can return the token regex and parse table.
        return [this.tokenRegex, this.parseTable, startSymbol];
    }
}